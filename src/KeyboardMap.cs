using System;
using System.Collections.Generic;

// PC/AT set-1 make scan codes to USB HID Keyboard/Keypad usages.
// Physical scans take priority so the foreground Windows layout does the text translation.
internal static class KeyboardMap
{
    static readonly Dictionary<int, byte> Scans = Build();
    static Dictionary<int, byte> Build()
    {
        var map = new Dictionary<int,byte>();
        void Put(int s,int u) => map.Add(s,(byte)u);
        void Row(int first, params byte[] usages) {for(int i=0;i<usages.Length;i++) Put(first+i,usages[i]);}
        Put(0x01,0x29); Row(0x02,0x1e,0x1f,0x20,0x21,0x22,0x23,0x24,0x25,0x26,0x27);
        Row(0x0c,0x2d,0x2e,0x2a,0x2b);
        Row(0x10,0x14,0x1a,0x08,0x15,0x17,0x1c,0x18,0x0c,0x12,0x13);
        Row(0x1a,0x2f,0x30,0x28,0xe0);
        Row(0x1e,0x04,0x16,0x07,0x09,0x0a,0x0b,0x0d,0x0e,0x0f);
        Row(0x27,0x33,0x34,0x35,0xe1,0x31);
        Row(0x2c,0x1d,0x1b,0x06,0x19,0x05,0x11,0x10);
        Row(0x33,0x36,0x37,0x38,0xe5,0x55,0xe2,0x2c,0x39);
        for(int i=0;i<10;i++) Put(0x3b+i,0x3a+i);
        Row(0x45,0x53,0x47,0x5f,0x60,0x61,0x56,0x5c,0x5d,0x5e,0x57,0x59,0x5a,0x5b,0x62,0x63);
        Put(0x56,0x64); Put(0x57,0x44);Put(0x58,0x45);
        Put(0xe01c,0x58);Put(0xe01d,0xe4);Put(0xe035,0x54);Put(0xe037,0x46);Put(0xe038,0xe6);
        Put(0xe047,0x4a);Put(0xe048,0x52);Put(0xe049,0x4b);Put(0xe04b,0x50);Put(0xe04d,0x4f);
        Put(0xe04f,0x4d);Put(0xe050,0x51);Put(0xe051,0x4e);Put(0xe052,0x49);Put(0xe053,0x4c);
        Put(0xe05b,0xe3);Put(0xe05c,0xe7);Put(0xe05d,0x65);
        return map;
    }
    internal static byte Translate(uint vk,uint scan,uint flags)
    {
        // Explicit side-specific VKs remain unambiguous even if the client tags
        // NumLock/right-side keys with an unexpected extended flag.
        if(vk==0x90) return 0x53;
        if(vk==0xa0) return 0xe1;if(vk==0xa1)return 0xe5;
        if(vk==0xa2) return 0xe0;if(vk==0xa3)return 0xe4;
        if(vk==0xa4) return 0xe2;if(vk==0xa5)return 0xe6;
        if(vk==0x5b) return 0xe3;if(vk==0x5c)return 0xe7;if(vk==0x5d)return 0x65;
        if(vk==0xe7) return 0; // VK_PACKET is Unicode text, not a physical key.
        if(vk is 0x13 or 0x03) return 0x48; // Pause uses an E1 sequence, unlike NumLock.
        if(vk==0x2c) return 0x46;
        int s=(int)scan;
        if((flags&1)!=0 || (s&0xff00)==0xe000) s=0xe000|(s&0xff);
        if(Scans.TryGetValue(s,out byte usage)) return usage;
        // VK fallback is only for events with no usable physical scan.
        // F13-F24 often use extended vendor scan values; VK identifies them unambiguously.
        if(vk>=0x7c && vk<=0x87) return (byte)(0x68+vk-0x7c);
        if(scan!=0) return 0;
        if(vk>=0x41 && vk<=0x5a) return (byte)(4+vk-0x41);
        if(vk>=0x31 && vk<=0x39) return (byte)(0x1e+vk-0x31);
        if(vk==0x30) return 0x27;
        if(vk>=0x70 && vk<=0x7b) return (byte)(0x3a+vk-0x70);
        if(vk>=0x7c && vk<=0x87) return (byte)(0x68+vk-0x7c);
        if(vk>=0x61 && vk<=0x69) return (byte)(0x59+vk-0x61);
        return vk switch {
            0x08=>0x2a,0x09=>0x2b,0x0d=>(flags&1)!=0?(byte)0x58:(byte)0x28,
            0x1b=>0x29,0x20=>0x2c,0x14=>0x39,0x90=>0x53,0x91=>0x47,
            0x2d=>0x49,0x24=>0x4a,0x21=>0x4b,0x2e=>0x4c,0x23=>0x4d,0x22=>0x4e,
            0x27=>0x4f,0x25=>0x50,0x28=>0x51,0x26=>0x52,
            0x60=>0x62,0x6e=>0x63,0x6f=>0x54,0x6a=>0x55,0x6d=>0x56,0x6b=>0x57,
            0xa0=>0xe1,0xa1=>0xe5,0xa2=>0xe0,0xa3=>0xe4,0xa4=>0xe2,0xa5=>0xe6,
            0x10=>0xe1,0x11=>(flags&1)!=0?(byte)0xe4:(byte)0xe0,0x12=>(flags&1)!=0?(byte)0xe6:(byte)0xe2,
            0x5b=>0xe3,0x5c=>0xe7,0x5d=>0x65,
            0xba=>0x33,0xbb=>0x2e,0xbc=>0x36,0xbd=>0x2d,0xbe=>0x37,0xbf=>0x38,
            0xc0=>0x35,0xdb=>0x2f,0xdc=>0x31,0xdd=>0x30,0xde=>0x34,0xe2=>0x64,_=>0
        };
    }
    // HID Consumer page usages for standard Windows media/browser virtual keys.
    internal static ushort Consumer(uint vk) => vk switch {
        0xad=>0xe2,0xae=>0xea,0xaf=>0xe9,0xb0=>0xb5,0xb1=>0xb6,0xb2=>0xb7,0xb3=>0xcd,
        0xa6=>0x224,0xa7=>0x225,0xa8=>0x227,0xa9=>0x226,0xaa=>0x221,0xab=>0x22a,0xac=>0x223,
        0xb4=>0x18a,0xb5=>0x183,0xb6=>0x194,0xb7=>0x192,_=>0
    };
    internal static void SelfTest()
    {
        if(Consumer(0xad)!=0xe2 || Consumer(0xaf)!=0xe9 || Consumer(0x57)!=0) throw new Exception("Consumer mapping failed");
        // Edge cases that silently turn game controls into other keys.
        var cases=new (uint Vk,uint Scan,uint Flags,byte Usage)[] {
            (0x57,0x11,0,0x1a),(0x41,0x1e,0,0x04),(0x53,0x1f,0,0x16),(0x44,0x20,0,0x07),
            (0x11,0x1d,0,0xe0),(0x11,0x1d,1,0xe4),(0xa1,0x36,0,0xe5),
            (0x12,0x38,0,0xe2),(0x12,0x38,1,0xe6),
            (0x26,0x48,1,0x52),(0x68,0x48,0,0x60),(0x0d,0x1c,1,0x58),
            (0x03,0x46,1,0x48),(0x13,0x45,0,0x48),(0x90,0x45,1,0x53),(0xa1,0x36,1,0xe5),(0x5c,0x5c,0,0xe7),(0x90,0x45,0,0x53),(0x2c,0x37,1,0x46),
            (0x57,0,0,0x1a),(0x57,0x999,0,0),(0xe7,0x41,0,0),(0x27,0xe04d,0,0x4f),
            (0x7c,0x64,0,0x68),(0x87,0x76,0,0x73),(0xe2,0x56,0,0x64),
            (0x20,0x39,0,0x2c),(0x08,0x0e,0,0x2a),(0x77,0x42,0,0x41)
        };
        foreach(var c in cases) if(Translate(c.Vk,c.Scan,c.Flags)!=c.Usage) throw new Exception($"Map failed VK={c.Vk:X} scan={c.Scan:X}");
        var state=new KeyboardState();
        state.Set(0xe1,true);state.Set(0x1a,true);state.Set(0x04,true);
        if(state.Modifiers!=2 || state.KeyCount!=2) throw new Exception("Chord state failed");
        if(state.Set(0x1a,true) || state.KeyCount!=2) throw new Exception("Repeated DOWN duplicated key");
        state.Set(0x1a,false);
        if(state.KeyCount!=1 || state.Modifiers!=2) throw new Exception("Partial chord release failed");
        state.Set(0x04,false);state.Set(0xe1,false);
        if(state.KeyCount!=0 || state.Modifiers!=0) throw new Exception("Release sequence failed");
        for(byte u=4;u<12;u++)state.Set(u,true);
        state.Set(0xe4,true);state.Set(0xe5,true);
        if(state.KeyCount!=8 || state.Modifiers!=0x30) throw new Exception("NKRO eight-key chord failed");
        state.Set(7,false);
        if(state.KeyCount!=7)throw new Exception("Independent NKRO release failed");
        state.Clear();
        if(state.KeyCount!=0 || state.Modifiers!=0) throw new Exception("Emergency clear failed");
    }
}

internal sealed class KeyboardState
{
    readonly SortedSet<byte> Held = new();
    public bool Set(byte usage,bool down) => down?Held.Add(usage):Held.Remove(usage);
    public void Clear() => Held.Clear();
    public IEnumerable<byte> NonModifiers => Held.Where(u=>u<0xe0);
    public int KeyCount => Held.Count(u=>u<0xe0);
    public byte Modifiers { get {byte m=0;foreach(byte u in Held)if(u>=0xe0 && u<=0xe7)m|=(byte)(1<<(u-0xe0));return m;} }
}
